class PDFGenerator:
    """Generates verified PDF artifacts from HTML and Markdown content."""

    @staticmethod
    def sanitize_filename(name: str) -> str:
        """Sanitize filename to prevent path traversal or filesystem incompatibilities."""
        # Remove paths and invalid characters
        clean = re.sub(r'[\\/*?:"<>|]', "", name)
        clean = re.sub(r"\s+", "_", clean).strip("._ ")
        if not clean:
            clean = f"zero_report_{datetime.now().strftime('%Y%m%d_%H%M%S')}"
        if not clean.lower().endswith(".pdf"):
            clean += ".pdf"
        return clean

    @classmethod
    def create_html_report(
        cls,
        title: str,
        body_markdown: str,
        subtitle: str = "Executive Intelligence Document",
        author: str = "ZERO AI Assistant",
    ) -> str:
        """Convert Markdown to styled executive HTML document."""
        html_body = markdown.markdown(
            body_markdown,
            extensions=["tables", "fenced_code", "nl2br", "sane_lists"],
        )

        date_str = datetime.now().strftime("%B %d, %Y - %H:%M:%S")

        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{title}</title>
<style>
{EXECUTIVE_DOCUMENT_CSS}
</style>
</head>
<body>

<div class="document-header">
    <div class="header-title-box">
        <h1>{title}</h1>
        <p class="header-meta">{subtitle} &bull; Generated by {author}</p>
    </div>
    <div class="header-badge">ZERO // ARTIFACT</div>
</div>

<div class="document-content">
{html_body}
</div>

<div class="document-footer">
    <span>Classification: Executive Internal &bull; Zero Personal AI</span>
    <span>Date: {date_str}</span>
</div>

</body>
</html>
"""
        return html

    @classmethod
    def generate_pdf(
        cls,
        html_content: str,
        filename: str,
        exports_dir: Path | None = None,
    ) -> Path:
        """
        Render HTML string to PDF using Playwright Chromium.
        Verifies file exists, size > 0, and starts with %PDF- signature.
        """
        target_dir = exports_dir or get_exports_dir()
        target_dir.mkdir(parents=True, exist_ok=True)

        safe_name = cls.sanitize_filename(filename)
        output_pdf_path = (target_dir / safe_name).resolve()

        # Security check: Ensure output path stays strictly inside target_dir
        if not str(output_pdf_path).startswith(str(target_dir.resolve())):
            raise ValueError("Path traversal attempt detected in PDF filename.")

        try:
            from playwright.sync_api import sync_playwright
            with sync_playwright() as p:
                browser = p.chromium.launch(headless=True)
                page = browser.new_page()
                page.set_content(html_content, wait_until="networkidle")
                page.pdf(
                    path=str(output_pdf_path),
                    format="A4",
                    print_background=True,
                    margin={"top": "15mm", "bottom": "15mm", "left": "15mm", "right": "15mm"},
                )
                browser.close()

        except Exception as e:
            logger.error("Playwright PDF generation failed: %s", e)
            # Create a readable HTML fallback file if Chromium fails
            fallback_html = output_pdf_path.with_suffix(".html")
            fallback_html.write_text(html_content, encoding="utf-8")
            raise RuntimeError(
                f"Failed to generate PDF via Playwright: {e}. "
                f"An HTML copy was preserved at: {fallback_html.name}"
            )

        # Verification step
        if not output_pdf_path.exists():
            raise FileNotFoundError(f"PDF generation failed: {output_pdf_path} was not created.")

        file_size = output_pdf_path.stat().st_size
        if file_size == 0:
            output_pdf_path.unlink(missing_ok=True)
            raise ValueError("Generated PDF file was empty (0 bytes).")

        # Validate PDF signature (%PDF-)
        with output_pdf_path.open("rb") as f:
            header = f.read(5)
            if not header.startswith(b"%PDF-"):
                output_pdf_path.unlink(missing_ok=True)
                raise ValueError("Generated file is missing valid %PDF magic header.")

        logger.info("PDF artifact verified and created: %s (%d bytes)", safe_name, file_size)
        return output_pdf_path

    def generate_document(self, title: str, body_html: str, doc_type: str = "Report") -> dict:
        """Generate PDF from HTML body content and return metadata dictionary."""
        date_str = datetime.now().strftime("%B %d, %Y - %H:%M:%S")
        html = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>{title}</title>
<style>
{EXECUTIVE_DOCUMENT_CSS}
</style>
</head>
<body>
<div class="document-header">
    <div class="header-title-box">
        <h1>{title}</h1>
        <p class="header-meta">{doc_type} &bull; Generated by ZERO AI</p>
    </div>
    <div class="header-badge">ZERO // ARTIFACT</div>
</div>
<div class="document-content">
{body_html}
</div>
<div class="document-footer">
    <span>Classification: Executive Internal &bull; Zero Personal AI</span>
    <span>Date: {date_str}</span>
</div>
</body>
</html>"""
        path = self.generate_pdf(html, filename=self.sanitize_filename(title))
        return {
            "filename": path.name,
            "filepath": str(path),
            "size_bytes": path.stat().st_size,
        }


_pdf_generator_instance: PDFGenerator | None = None


def get_pdf_generator() -> PDFGenerator:
    """Return singleton PDFGenerator instance."""
    global _pdf_generator_instance
    if _pdf_generator_instance is None:
        _pdf_generator_instance = PDFGenerator()
    return _pdf_generator_instance
